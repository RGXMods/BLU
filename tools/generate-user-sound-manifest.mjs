#!/usr/bin/env node
// Finds user sound files at ANY depth under the AddOns folder and writes them to a small
// companion addon, BLU_UserSounds, that BLU reads.
//
// Why a tool: a WoW addon cannot list folders; it can only test paths it already knows. BLU
// can therefore only guess fixed names a level or two deep. This script walks the whole
// AddOns tree (unlimited depth) and hands BLU the exact paths. The companion addon lives in
// its own folder, so BLU updates never overwrite it.
//
// Usage:
//   node tools/generate-user-sound-manifest.mjs [--addons <AddOns folder>]
//        [--include <folder> ...] [--exclude <folder> ...] [--max <count>] [--dry-run]
//   --addons   Interface/AddOns folder (default: $WOW_ADDONS, else common install locations)
//   --include  only scan these top-level AddOns folders (repeatable; default: all)
//   --exclude  also skip these top-level folders (repeatable)
//   --max      stop after this many files (default 3000)
// After running, /reload in game (a new file also needs a full game restart to be playable).

import fs from "node:fs";
import path from "node:path";

const SOUND_EXTENSIONS = new Set([".ogg", ".mp3", ".wav"]);
const ALWAYS_SKIP = [/^BLU/i, /^Blizzard_/i, /^\./];
const COMPANION = "BLU_UserSounds";

export function parseArgs(argv) {
  const opts = { include: [], exclude: [], max: 3000, dryRun: false, addons: process.env.WOW_ADDONS || null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--addons") opts.addons = argv[++i];
    else if (a === "--include") opts.include.push(argv[++i]);
    else if (a === "--exclude") opts.exclude.push(argv[++i]);
    else if (a === "--max") opts.max = Number(argv[++i]);
    else if (a === "--dry-run") opts.dryRun = true;
    else throw new Error(`unknown argument: ${a}`);
  }
  return opts;
}

export function defaultAddonDirs() {
  const roots = ["C:\\Program Files (x86)\\World of Warcraft", "C:\\Program Files\\World of Warcraft", "/Applications/World of Warcraft"];
  const flavors = ["_forever_", "_retail_", "_classic_", "_classic_era_", "_beta_", "_ptr_"];
  return roots.flatMap((root) => flavors.map((f) => path.join(root, f, "Interface", "AddOns")));
}

// Every sound file under `addonsDir`, any depth, as { rel: "Folder\\Sub\\file.ogg" }.
export function findSounds(addonsDir, { include = [], exclude = [], max = 3000 } = {}) {
  const found = [];
  const skipTop = (name) =>
    ALWAYS_SKIP.some((re) => re.test(name)) || exclude.some((e) => e.toLowerCase() === name.toLowerCase()) ||
    (include.length > 0 && !include.some((i) => i.toLowerCase() === name.toLowerCase()));
  const walk = (dir, relParts) => {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      if (found.length >= max) return;
      if (relParts.length === 0 && skipTop(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full, [...relParts, entry.name]);
      else if (entry.isFile() && SOUND_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
        found.push({ parts: [...relParts, entry.name] });
      }
    }
  };
  walk(addonsDir, []);
  return found.map(({ parts }) => ({
    file: ["Interface", "AddOns", ...parts].join("\\"),
    name: parts.slice(0, -1).slice(-2).concat(path.basename(parts[parts.length - 1], path.extname(parts[parts.length - 1]))).join(" / "),
  }));
}

const luaString = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

export function renderManifest(sounds) {
  const lines = [
    "-- GENERATED by BLU's tools/generate-user-sound-manifest.mjs. Re-run it after adding sounds.",
    "BLU_UserCustomSoundManifest = BLU_UserCustomSoundManifest or {}",
    "local manifest = BLU_UserCustomSoundManifest",
  ];
  for (const s of sounds) lines.push(`manifest[#manifest + 1] = { file = ${luaString(s.file)}, name = ${luaString(s.name)} }`);
  return lines.join("\n") + "\n";
}

export function renderToc() {
  return [
    "## Interface: 120105, 16001, 11509, 20506, 38002, 40402, 50504",
    "## Title: BLU User Sounds",
    "## Notes: Sound files found for BLU at any folder depth. Generated by BLU's tools/generate-user-sound-manifest.mjs.",
    "## Version: generated",
    "",
    "manifest.lua",
    "",
  ].join("\n");
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const addons = opts.addons || defaultAddonDirs().find((d) => fs.existsSync(d));
  if (!addons || !fs.existsSync(addons)) {
    console.error("Could not find the AddOns folder. Pass --addons \"<path to Interface/AddOns>\" or set WOW_ADDONS.");
    process.exit(1);
  }
  const sounds = findSounds(addons, opts);
  console.log(`Found ${sounds.length} sound file(s) under ${addons} (any depth).`);
  if (sounds.length >= opts.max) console.warn(`Stopped at --max ${opts.max}; use --include to narrow the search or raise --max.`);
  if (opts.dryRun) { for (const s of sounds.slice(0, 50)) console.log("  " + s.file); return; }
  const out = path.join(addons, COMPANION);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, `${COMPANION}.toc`), renderToc());
  fs.writeFileSync(path.join(out, "manifest.lua"), renderManifest(sounds));
  console.log(`Wrote ${out}. Run /reload in game (restart the game for brand-new files).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) main();
